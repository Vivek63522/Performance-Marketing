export function getServiceBySlug(slug) {
  if (!slug) return companyServices[0];
  const normalized = slug.toLowerCase().trim();
  const found = companyServices.find(
    (s) =>
      s.slug === normalized ||
      (s.aliases && s.aliases.includes(normalized)) ||
      s.id === normalized,
  );
  return found || companyServices[0];
}
